// ─── Colors ───────────────────────────────────────────────────────────────────

function cssVar(name) {
  return getComputedStyle(document.documentElement).getPropertyValue(name).trim();
}

// Any CSS color (a token may be color-mix, oklch, a name) → what the canvas normalizes it to.
let _ctx = null;
function normalizeColor(value, fallback) {
  _ctx ??= document.createElement("canvas").getContext("2d");
  _ctx.fillStyle = fallback;
  if (value) _ctx.fillStyle = value;
  return _ctx.fillStyle;
}

function resolveColors(overrides = {}) {
  const pick = (key, token, fallback) => toPixiColor(normalizeColor(overrides[key] || (token && cssVar(token)), fallback));
  return {
    // Obsidian's palette: quiet grey nodes, the page you are on in the accent, thin light lines.
    node:           pick("node", "--text-light", "#6e6e6e"),
    node_current:   pick("node_current", "--accent-color", "#d2691e"),
    node_tag:       pick("node_tag", "--accent-muted", "#7a9e7e"),
    link:           pick("link", "--text-light", "#888888"),
    link_highlight: pick("link_highlight", "--accent-color", "#d2691e"),
    text:           pick("text", "--text-color", "#333333"),
    font:           cssVar("--font-body") || "sans-serif",
  };
}

// Day and night: when the system's scheme or the visitor's own choice (html[data-sky]) changes,
// the colors are read again in place and the graph repaints.
function followScheme(colors, overrides, repaint) {
  const refresh = () => { Object.assign(colors, resolveColors(overrides)); repaint(); };
  window.matchMedia?.("(prefers-color-scheme: dark)").addEventListener?.("change", refresh);
  new MutationObserver(refresh).observe(document.documentElement, { attributes: true, attributeFilter: ["data-sky"] });
}

// ─── Data filtering ───────────────────────────────────────────────────────────

function filterTags(graphData, showTags) {
  if (showTags) return graphData;
  const tagIds = new Set(
    graphData.nodes.filter((n) => n.type === "tag").map((n) => n.id)
  );
  return {
    nodes: graphData.nodes.filter((n) => n.type !== "tag"),
    links: graphData.links.filter((l) => {
      const s = typeof l.source === "object" ? l.source.id : l.source;
      const t = typeof l.target === "object" ? l.target.id : l.target;
      return !tagIds.has(s) && !tagIds.has(t);
    }),
  };
}

/**
 * BFS to collect nodes within `depth` hops of currentUrl (undirected).
 */
function getLocalGraph(graphData, currentUrl, depth) {
  const normalise = (u) => (u.endsWith("/") ? u : u + "/");
  const current = normalise(currentUrl);

  const visited = new Set([current]);
  let frontier = [current];

  for (let hop = 0; hop < depth; hop++) {
    const next = [];
    for (const url of frontier) {
      for (const link of graphData.links) {
        const s = normalise(typeof link.source === "object" ? link.source.id : link.source);
        const t = normalise(typeof link.target === "object" ? link.target.id : link.target);
        const neighbor = s === url ? t : t === url ? s : null;
        if (neighbor && !visited.has(neighbor)) {
          visited.add(neighbor);
          next.push(neighbor);
        }
      }
    }
    frontier = next;
    if (!frontier.length) break;
  }

  const nodes = graphData.nodes.filter((n) => visited.has(normalise(n.id)));
  const nodeIds = new Set(nodes.map((n) => normalise(n.id)));
  const links = graphData.links.filter((l) => {
    const s = normalise(typeof l.source === "object" ? l.source.id : l.source);
    const t = normalise(typeof l.target === "object" ? l.target.id : l.target);
    return nodeIds.has(s) && nodeIds.has(t);
  });

  return { nodes, links };
}

// ─── Drawing (Quartz's approach: d3-force moves, PixiJS draws) ───────────────

const idOf = (end) => (typeof end === "object" ? end.id : end);

/**
 * Draws a graph into `host`. Returns { resize, restyle, setData, destroy }.
 * `look` is GRAPH_LOOK.local or .full; `colors` from resolveColors (mutated in place on restyle).
 */
async function drawGraph(L, host, data, { currentUrl, colors, look, onOpen, tooltip, height }) {
  const { PIXI } = L;
  const normalise = (u) => (u.endsWith("/") ? u : u + "/");
  const current = normalise(currentUrl);
  let width = host.clientWidth || 500;

  const app = new PIXI.Application();
  await app.init({
    width, height, antialias: true, autoStart: false, autoDensity: true,
    backgroundAlpha: 0, resolution: window.devicePixelRatio || 1, preference: "webgl",
  });
  host.appendChild(app.canvas);
  app.canvas.style.touchAction = "none";

  const world = new PIXI.Container();
  const linkG = new PIXI.Graphics();
  const nodeLayer = new PIXI.Container();
  const labelLayer = new PIXI.Container();
  world.addChild(linkG, nodeLayer, labelLayer);
  app.stage.addChild(world);

  let nodes = [], links = [], sim = null, hovered = null, neighbours = new Set(), nearCurrent = new Set();
  let transform = L.zoomIdentity, dragging = null, running = false, destroyed = false;

  const isCurrent = (n) => normalise(n.id) === current;
  const nodeColor = (n) => (isCurrent(n) ? colors.node_current : n.type === "tag" ? colors.node_tag : colors.node);

  function paintNode(n) {
    const c = nodeColor(n);
    n.gfx.clear().circle(0, 0, n.r).fill({ color: c.color, alpha: isCurrent(n) ? 1 : 0.8 });
    if (n.type === "tag") n.gfx.stroke({ width: 1.2, color: colors.node_tag.color, alpha: 1 });
    n.label.style.fill = colors.text.color;
    n.label.style.fontFamily = colors.font;
  }

  function build(graphData) {
    sim?.stop();
    nodeLayer.removeChildren().forEach((c) => c.destroy());
    labelLayer.removeChildren().forEach((c) => c.destroy());
    const old = new Map(nodes.map((n) => [n.id, n]));
    const deg = degrees(graphData.links);
    nodes = graphData.nodes.map((src) => {
      const was = old.get(src.id);
      const n = { ...src, x: was?.x, y: was?.y, r: nodeRadius(deg.get(src.id)), a: 1, la: 0 };
      n.gfx = new PIXI.Graphics();
      n.label = new PIXI.Text({
        text: shortLabel(src.title || src.id),
        anchor: { x: 0.5, y: -0.35 },
        style: { fontSize: look.fontSize, fill: colors.text.color, fontFamily: colors.font },
        resolution: (window.devicePixelRatio || 1) * 3,
      });
      n.label.alpha = 0;
      paintNode(n);
      nodeLayer.addChild(n.gfx);
      labelLayer.addChild(n.label);
      return n;
    });
    const byId = new Map(nodes.map((n) => [n.id, n]));
    links = graphData.links
      .map((l) => ({ source: byId.get(idOf(l.source)), target: byId.get(idOf(l.target)), a: 1 }))
      .filter((l) => l.source && l.target);
    // The page you are on and the pages it touches directly keep their names showing.
    nearCurrent = new Set();
    for (const l of links) {
      if (isCurrent(l.source)) nearCurrent.add(l.target.id);
      if (isCurrent(l.target)) nearCurrent.add(l.source.id);
    }

    sim = L.forceSimulation(nodes)
      .force("charge", L.forceManyBody().strength(-100 * look.repel))
      .force("center", L.forceCenter().strength(look.center))
      .force("link", L.forceLink(links).distance(look.linkDistance))
      .force("collide", L.forceCollide((n) => n.r + 4).iterations(3))
      .force("x", L.forceX(0).strength(look.gravity))
      .force("y", L.forceY(0).strength(look.gravity))
      .stop();
    // Settle most of the way before anyone sees it, then let the last bit float into place.
    for (let i = 0; i < look.warmup; i++) sim.tick();
    sim.alpha(0.12).on("tick", wake).restart();
  }

  // ── Hover: one neighbourhood lit, the rest dimmed ──
  function setHover(n) {
    if (hovered) hovered.label.text = shortLabel(hovered.title || hovered.id);
    if (n) n.label.text = n.title || n.id;
    hovered = n;
    neighbours = new Set();
    if (n) {
      neighbours.add(n.id);
      for (const l of links) {
        if (l.source === n) neighbours.add(l.target.id);
        if (l.target === n) neighbours.add(l.source.id);
      }
      tooltip?.show(n);
    } else tooltip?.hide();
    app.canvas.style.cursor = n ? "pointer" : "";
    wake();
  }

  // The node under a screen point (a little generous, so fingers can hit small nodes).
  function nodeAt(px, py) {
    const [wx, wy] = transform.invert([px, py]);
    let best = null, bestD = Infinity;
    for (const n of nodes) {
      const d = Math.hypot(n.x - wx, n.y - wy);
      if (d < n.r + 6 / transform.k && d < bestD) { best = n; bestD = d; }
    }
    return best;
  }

  app.canvas.addEventListener("pointermove", (e) => {
    if (dragging) return;
    const r = app.canvas.getBoundingClientRect();
    const n = nodeAt(e.clientX - r.left, e.clientY - r.top);
    if (n !== hovered) setHover(n);
  });
  app.canvas.addEventListener("pointerleave", () => { if (!dragging) setHover(null); });

  // ── Drag a node (and click = open); otherwise pan and zoom ──
  const canvasSel = L.select(app.canvas);
  let downAt = 0, moved = 0;
  canvasSel.call(
    L.drag()
      .container(() => app.canvas)
      .subject((e) => nodeAt(e.x, e.y))
      .on("start", (e) => {
        dragging = e.subject; downAt = Date.now(); moved = 0;
        if (!e.active) sim.alphaTarget(0.3).restart();
        e.subject.fx = e.subject.x; e.subject.fy = e.subject.y;
      })
      .on("drag", (e) => {
        moved += Math.abs(e.dx) + Math.abs(e.dy);
        const [wx, wy] = transform.invert([e.x, e.y]);
        e.subject.fx = wx; e.subject.fy = wy;
      })
      .on("end", (e) => {
        if (!e.active) sim.alphaTarget(0);
        e.subject.fx = null; e.subject.fy = null;
        const n = e.subject;
        dragging = null;
        if (Date.now() - downAt < 400 && moved < 6) onOpen?.(n);
      }),
  );
  const zoomer = L.zoom()
    .scaleExtent([0.2, 6])
    .on("zoom", (e) => { transform = e.transform; wake(); });
  canvasSel.call(zoomer).on("dblclick.zoom", null);

  function fit() {
    const t = fitTransform(nodes, width, height, { pad: 40, maxZoom: look.maxZoom });
    const target = L.zoomIdentity.translate(t.x, t.y).scale(t.k);
    canvasSel.call(zoomer.transform, target);
  }

  // ── One frame; keeps going only while something is moving ──
  function frame() {
    if (destroyed) return;
    let moving = sim.alpha() > sim.alphaMin() || Boolean(dragging);
    world.position.set(transform.x, transform.y);
    world.scale.set(transform.k);

    const zoomLabels = labelAlpha(transform.k, look.labelFade);
    for (const n of nodes) {
      const lit = !hovered || neighbours.has(n.id);
      let still;
      [n.a, still] = ease(n.a, lit ? 1 : 0.25); moving ||= still;
      const labelTarget = hovered
        ? (lit ? 1 : zoomLabels * 0.15)
        : restingLabelAlpha({ isCurrent: isCurrent(n), isNeighbour: look.neighbourLabels && nearCurrent.has(n.id), zoomAlpha: zoomLabels });
      [n.la, still] = ease(n.la, labelTarget); moving ||= still;
      n.gfx.position.set(n.x, n.y);
      n.gfx.alpha = n.a;
      n.label.position.set(n.x, n.y + n.r);
      n.label.alpha = n.la;
      // Labels keep a steady size on screen until you zoom in close, then grow with the page.
      n.label.scale.set(Math.max(1 / transform.k, 0.6) * (hovered === n ? 1.15 : 1));
    }

    linkG.clear();
    for (const l of links) {
      const lit = hovered && (l.source === hovered || l.target === hovered);
      let still;
      [l.a, still] = ease(l.a, !hovered ? 1 : lit ? 1 : 0.2); moving ||= still;
      const c = lit ? colors.link_highlight : colors.link;
      linkG.moveTo(l.source.x, l.source.y).lineTo(l.target.x, l.target.y)
        .stroke({ width: (lit ? 1.4 : 0.8) / Math.max(transform.k, 0.5), color: c.color, alpha: (lit ? 0.9 : 0.45) * l.a });
    }

    app.renderer.render(app.stage);
    if (moving) requestAnimationFrame(frame);
    else running = false;
  }
  function wake() {
    if (running || destroyed) return;
    running = true;
    requestAnimationFrame(frame);
  }

  build(data);
  fit();
  wake();

  return {
    resize(w) {
      width = w || host.clientWidth || width;
      app.renderer.resize(width, height);
      fit();
      wake();
    },
    restyle() { nodes.forEach(paintNode); wake(); },
    setData(d) { build(d); fit(); wake(); },
    destroy() {
      destroyed = true;
      sim?.stop();
      tooltip?.hide();
      app.destroy(true, { children: true });
    },
  };
}

// ─── Hover tooltip (shared) ───────────────────────────────────────────────────

/**
 * Simple mouse-following tooltip appended to document.body.
 * Avoids all coordinate conversion problems.
 * Returns { attach(canvasEl), show(node), hide() }.
 */
function makeTooltip() {
  const el = document.createElement("div");
  el.style.cssText = [
    "position:fixed",
    "pointer-events:none",
    "display:none",
    "z-index:9999",
    "background:var(--bg-color,#fffaf0)",
    "border:1px solid var(--border-color,#e0d8cc)",
    "border-radius:6px",
    "padding:6px 8px",
    "box-shadow:0 2px 8px rgba(0,0,0,0.18)",
    "width:150px",
    "font-family:var(--font-body,sans-serif)",
    "font-size:12px",
    "color:var(--text-color,#333)",
    "line-height:1.4",
  ].join(";");
  document.body.appendChild(el);

  // Track the mouse over the graph's element
  function attach(canvasEl) {
    canvasEl.addEventListener("pointermove", (e) => {
      if (el.style.display === "none") return;
      el.style.left = (e.clientX + 14) + "px";
      el.style.top  = (e.clientY - el.offsetHeight - 14) + "px";
    });
    canvasEl.addEventListener("pointerleave", () => hide());
  }

  function show(node, e) {
    el.innerHTML = "";

    if (node.image) {
      const img = document.createElement("img");
      img.src = node.image;
      img.alt = "";
      img.style.cssText = "display:block;width:100%;max-height:90px;object-fit:cover;border-radius:3px;margin-bottom:5px;";
      el.appendChild(img);
    }

    const nameEl = document.createElement("div");
    nameEl.style.cssText = "font-weight:600;word-break:break-word;text-align:center;";
    nameEl.textContent = node.title || node.id;
    el.appendChild(nameEl);

    if (node.subtitle) {
      const subEl = document.createElement("div");
      subEl.style.cssText = "font-size:10px;opacity:0.7;word-break:break-word;text-align:center;margin-top:3px;";
      subEl.textContent = node.subtitle;
      el.appendChild(subEl);
    }

    el.style.display = "block";
  }

  function hide() {
    el.style.display = "none";
  }

  return { attach, show, hide, remove: () => el.remove() };
}

// ─── Inline graph ─────────────────────────────────────────────────────────────

const LOCAL_HEIGHT = 420;

function renderGraph(container, graphData, currentUrl, settings) {
  let showTags = settings.show_tags;
  let localData = getLocalGraph(filterTags(graphData, showTags), currentUrl, settings.depth);

  // Hide if only_if_linked and this page has no connections
  if (settings.only_if_linked && localData.nodes.length <= 1) {
    container.style.display = "none";
    return;
  }

  // --- Build container structure ---
  const header = document.createElement("div");
  header.className = "graph-header";

  const title = document.createElement("span");
  title.className = "graph-title";
  title.textContent = "Connections";
  header.appendChild(title);

  const buttons = document.createElement("span");
  buttons.className = "graph-buttons";
  header.appendChild(buttons);

  const tagsBtn = document.createElement("button");
  tagsBtn.className = "graph-full-btn";
  tagsBtn.textContent = showTags ? "Hide tags" : "Show tags";
  buttons.appendChild(tagsBtn);

  if (settings.show_full_graph) {
    const fullBtn = document.createElement("button");
    fullBtn.className = "graph-full-btn";
    fullBtn.textContent = "Full graph";
    fullBtn.addEventListener("click", () => openFullGraph(filterTags(graphData, showTags), currentUrl, settings));
    buttons.appendChild(fullBtn);
  }

  const canvasDiv = document.createElement("div");
  canvasDiv.className = "graph-canvas";
  canvasDiv.style.height = LOCAL_HEIGHT + "px";
  container.appendChild(header);
  container.appendChild(canvasDiv);

  const colors = resolveColors(settings.colors);
  const tooltip = makeTooltip();
  tooltip.attach(canvasDiv);
  let drawn = null;
  let starting = false;

  async function start() {
    if (drawn || starting) return;
    starting = true;
    try {
      const L = await loadLibs();
      drawn = await drawGraph(L, canvasDiv, localData, {
        currentUrl, colors, look: GRAPH_LOOK.local, tooltip, height: LOCAL_HEIGHT,
        onOpen: (n) => { window.location.href = n.id; },
      });
      followScheme(colors, settings.colors, () => drawn?.restyle());
    } catch (e) {
      console.warn("[graph] could not draw:", e?.message || e);
    } finally {
      starting = false;
    }
  }

  // Load the libraries only when the graph comes near the screen (it sits at the page's bottom).
  const io = new IntersectionObserver((entries) => {
    if (entries.some((en) => en.isIntersecting && canvasDiv.clientWidth > 0)) { io.disconnect(); start(); }
  }, { rootMargin: "400px" });
  io.observe(canvasDiv);

  // Inside an object that opens (a marble), measure again once it is open.
  container.closest(".bloob-object")?.addEventListener("bloob:open", () => setTimeout(() => drawn?.resize(canvasDiv.clientWidth), 60));
  let resizeTimer;
  addEventListener("resize", () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(() => drawn?.resize(canvasDiv.clientWidth), 150);
  });

  tagsBtn.addEventListener("click", () => {
    showTags = !showTags;
    tagsBtn.textContent = showTags ? "Hide tags" : "Show tags";
    localData = getLocalGraph(filterTags(graphData, showTags), currentUrl, settings.depth);
    drawn?.setData(localData);
  });
}

// ─── Full graph modal ─────────────────────────────────────────────────────────

function openFullGraph(graphData, currentUrl, settings) {
  let showTags = settings.show_tags;

  const overlay = document.createElement("div");
  overlay.className = "graph-modal-overlay";
  const modal = document.createElement("div");
  modal.className = "graph-modal";

  const closeBtn = document.createElement("button");
  closeBtn.className = "graph-modal-close";
  closeBtn.setAttribute("aria-label", "Close full graph");
  closeBtn.textContent = "×";

  const tagsBtn = document.createElement("button");
  tagsBtn.className = "graph-full-btn";
  tagsBtn.style.cssText = "position:absolute;top:10px;left:14px;z-index:1;";
  tagsBtn.textContent = showTags ? "Hide tags" : "Show tags";

  const canvasDiv = document.createElement("div");
  canvasDiv.className = "graph-modal-canvas";

  modal.append(closeBtn, tagsBtn, canvasDiv);
  overlay.appendChild(modal);
  document.body.appendChild(overlay);

  const colors = resolveColors(settings.colors);
  const tooltip = makeTooltip();
  tooltip.attach(canvasDiv);
  let drawn = null;
  let closed = false;

  const onKey = (e) => { if (e.key === "Escape") close(); };
  function close() {
    closed = true;
    drawn?.destroy();
    tooltip.remove();
    overlay.remove();
    document.removeEventListener("keydown", onKey);
  }
  closeBtn.addEventListener("click", close);
  overlay.addEventListener("click", (e) => { if (e.target === overlay) close(); });
  document.addEventListener("keydown", onKey);

  loadLibs().then(async (L) => {
    if (closed) return;
    canvasDiv.style.width = (modal.clientWidth || 820) + "px";
    canvasDiv.style.height = (modal.clientHeight || 600) + "px";
    drawn = await drawGraph(L, canvasDiv, filterTags(graphData, showTags), {
      currentUrl, colors, look: GRAPH_LOOK.full, tooltip, height: modal.clientHeight || 600,
      onOpen: (n) => { close(); window.location.href = n.id; },
    });
    if (closed) drawn.destroy();
    followScheme(colors, settings.colors, () => drawn?.restyle());
  }, (e) => console.warn("[graph] could not draw:", e?.message || e));

  tagsBtn.addEventListener("click", () => {
    showTags = !showTags;
    tagsBtn.textContent = showTags ? "Hide tags" : "Show tags";
    drawn?.setData(filterTags(graphData, showTags));
  });
}

// ─── Init ─────────────────────────────────────────────────────────────────────

async function init() {
  const containers = document.querySelectorAll(".graph-visualizer");
  if (!containers.length) return;

  const [graphData, siteSettings] = await Promise.all([fetchGraphData(), fetchGraphSettings()]);

  for (const container of containers) {
    const currentUrl = container.dataset.currentPage || window.location.pathname;

    let pageSettings = {};
    try { if (container.dataset.pageSettings) pageSettings = JSON.parse(container.dataset.pageSettings); } catch {}

    let instanceSettings = {};
    try { if (container.dataset.graphSettings) instanceSettings = JSON.parse(container.dataset.graphSettings); } catch {}

    const settings = {
      ...DEFAULTS,
      ...siteSettings,
      ...pageSettings,
      ...instanceSettings,
      colors: {
        ...(siteSettings.colors || {}),
        ...(pageSettings.colors || {}),
        ...(instanceSettings.colors || {}),
      },
    };

    renderGraph(container, graphData, currentUrl, settings);
  }
}

document.addEventListener("DOMContentLoaded", init);
