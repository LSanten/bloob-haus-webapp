// ─── Library loader (once, shared) ────────────────────────────────────────────

let _libs = null;
function loadLibs() {
  if (!_libs) {
    const load = (url) => import(/* @vite-ignore */ url);
    _libs = Promise.all(Object.values(LIBS).map(load)).then(([PIXI, force, zoom, drag, selection]) => ({
      PIXI, ...force, ...zoom, ...drag, ...selection,
    }));
    _libs.catch(() => { _libs = null; });
  }
  return _libs;
}

